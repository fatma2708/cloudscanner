"""Render generated infrastructure snippets back into valid HCL.

The rules engine attaches a ``generated_code`` structure to recommendations. This
module serializes that structure into human-readable Terraform source that users
can drop into their repository.

Validation pipeline:
  1. Structural validation (block types, resource names, reserved words)
  2. HCL syntax validation using the project's HCL2 parser
  3. Reference validation (generated code references only existing resources)
"""

from __future__ import annotations

from typing import Any


def _is_tf_expression(value: str) -> bool:
    """Return True if the string is a Terraform expression, not a literal string.

    Terraform expressions include:
      - resource references: aws_s3_bucket.name.id
      - variable references: var.name
      - local references: local.name
      - module references: module.name.output
      - data sources: data.aws_ami.latest.id
      - built-ins: count.index, each.key, self.name
      - string interpolation: ${...}
      - function calls: concat(...), lookup(...)
    """
    if not isinstance(value, str):
        return False
    # String interpolation is always an expression
    if "${" in value:
        return True
    # Function calls: name(...)
    if re.match(r"^[a-zA-Z_][a-zA-Z0-9_]*\(", value):
        return True
    # Terraform references: resource_type.name[.attr...]
    # or var.name, local.name, module.name, data.type.name, self.name
    if re.match(
        r"^(var|local|module|data|self|count|each)\.[a-zA-Z_]",
        value,
    ):
        return True
    # aws_/google_/azurerm_ resource references
    if re.match(
        r"^(aws|google|azurerm|digitalocean|hcloud|scaleway|ovh|oci|vultr|linode|cloudflare|kubernetes|openstack)_",
        value,
    ):
        return True
    return False


def _fmt_value(value: Any) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if value is None:
        return "null"
    if isinstance(value, (int, float)):
        return str(value)
    if isinstance(value, str):
        # Terraform expressions are rendered unquoted
        if _is_tf_expression(value):
            return value
        return f'"{value}"'
    if isinstance(value, dict):
        return _fmt_map(value)
    if isinstance(value, list):
        return _fmt_list(value)
    return f'"{value}"'


def _fmt_map(mapping: dict) -> str:
    if not mapping:
        return "{}"
    inner = ",\n    ".join(f"{k} = {_fmt_value(v)}" for k, v in mapping.items())
    return f"{{\n    {inner}\n  }}"


def _fmt_list(items: list) -> str:
    if not items:
        return "[]"
    inner = ",\n    ".join(_fmt_value(i) for i in items)
    return f"[\n    {inner}\n  ]"


def render_resource(block_type: str, name: str, config: dict, indent: int = 0) -> str:
    """Render a single ``resource "type" "name" { ... }`` block."""
    pad = "  " * indent
    lines = [f'{pad}resource "{block_type}" "{name}" {{']
    lines.append(_render_config(config, indent + 1))
    lines.append(f"{pad}}}")
    return "\n".join(lines)


def _render_config(config: dict, indent: int) -> str:
    pad = "  " * indent
    lines: list[str] = []
    for key, value in config.items():
        if isinstance(value, dict) and not _is_interpolation_like(value):
            lines.append(f"{pad}{key} {{")
            lines.append(_render_config(value, indent + 1))
            lines.append(f"{pad}}}")
        elif isinstance(value, list) and value and all(isinstance(i, dict) for i in value):
            for _idx, item in enumerate(value):
                lines.append(f"{pad}{key} {{")
                lines.append(_render_config(item, indent + 1))
                lines.append(f"{pad}}}")
        else:
            lines.append(f"{pad}{key} = {_fmt_value(value)}")
    return "\n".join(lines)


def _is_interpolation_like(value: dict) -> bool:
    return "$" in str(value.get("value", "")) or False


def render_generated_code(generated: dict | None) -> str:
    """Render the full generated_code payload into an HCL artifact string."""
    if not generated:
        return ""
    sections: list[str] = []
    sections.append("# Generated by CloudPilot AI — apply after review\n")
    for block_type, payload in generated.items():
        if not isinstance(payload, dict) or "name" not in payload:
            continue
        name = payload["name"]
        config = payload.get("config", {})
        sections.append(render_resource(block_type, name, config))
        sections.append("")
    return "\n".join(sections)


def render_optimized_project(blocks: list[dict]) -> str:
    """Render a full optimized project artifact from multiple resource blocks."""
    parts = ["# CloudPilot AI — optimized Terraform\n"]
    for block in blocks:
        parts.append(render_resource(block["resource_type"], block["name"], block["config"]))
        parts.append("")
    return "\n".join(parts)


