import re


def detect_provider_version(config_files: dict[str, str] | None = None) -> str | None:
    """Detect the AWS provider version from Terraform configuration.

    Checks:
    1. required_providers block for hashicorp/aws version constraint
    2. terraform.lock.hcl for exact resolved version
    3. provider "aws" block for any version hint

    Returns version string like "~> 5.0" or "5.31.0" or None if not detectable.
    """
    if not config_files:
        return None

    for path, content in config_files.items():
        if not content:
            continue

        # Check terraform.lock.hcl for exact version
        if path.endswith("terraform.lock.hcl"):
            match = re.search(r'version\s*=\s*"(\d+\.\d+\.\d+)"', content)
            if match:
                return match.group(1)

        # Check required_providers block
        match = re.search(
            r'aws\s*=\s*\{[^}]*version\s*=\s*"([^"]+)"',
            content,
            re.DOTALL,
        )
        if match:
            return match.group(1)

    return None


# Fields that should never appear as HCL attributes (Terraform reserved words)
_RESERVED_HCL_WORDS = {
    "resource", "data", "variable", "output", "locals",
    "module", "provider", "terraform", "moved", "import",
    "count", "for_each", "depends_on", "lifecycle",
}


def _parse_hcl_syntax(hcl_text: str) -> tuple[bool, list[str]]:
    """Attempt to parse the generated HCL text using the project's HCL2 parser.

    Returns (valid, errors).
    """
    try:
        from app.services.terraform.hcl import parse_hcl

        parse_hcl(hcl_text)
        return True, []
    except Exception as exc:
        return False, [f"HCL syntax error: {exc}"]


def validate_generated_block(block_type: str, name: str, config: dict) -> list[str]:
    """Validate a single generated resource block.

    Returns a list of validation error strings. Empty list = valid.
    """
    errors: list[str] = []

    # 1. Block type must be a known cloud resource type
    if not block_type.startswith(("aws_", "google_", "azurerm_")):
        errors.append(f"Unknown resource type '{block_type}' — not a recognized cloud provider prefix")
    elif block_type not in _KNOWN_AWS_RESOURCE_TYPES:
        errors.append(
            f"Resource type '{block_type}' has a valid provider prefix but is not in the "
            f"known-types list — verify it exists in your provider version"
        )

    # 2. Resource name must be a valid Terraform identifier
    if not name or not name[0].isalpha() and name[0] != "_":
        errors.append(f"Resource name '{name}' must start with a letter or underscore")
    if not all(c.isalnum() or c in ("_", "-") for c in name):
        errors.append(f"Resource name '{name}' contains invalid characters (use only a-z, 0-9, _, -)")

    # 3. Config keys must not be Terraform reserved words
    for key in config:
        if key in _RESERVED_HCL_WORDS:
            errors.append(f"Attribute '{key}' is a Terraform reserved word — not valid in a resource block")

    # 4. Check for empty config blocks
    if not config:
        errors.append(f"Resource '{block_type}.{name}' has an empty configuration block")

    # 5. Nested interpolation values should use proper HCL syntax
    def _check_interpolations(obj: Any, path: str = "") -> None:
        if isinstance(obj, dict):
            for k, v in obj.items():
                _check_interpolations(v, f"{path}.{k}")
        elif isinstance(obj, str):
            # Check for incomplete interpolation: ${...} without closing }
            if "${" in obj:
                opens = obj.count("${")
                closes = obj.count("}")
                if opens > closes:
                    errors.append(f"Unclosed interpolation at {path or 'root'}: '{obj[:80]}...'")

    _check_interpolations(config)

    return errors


def validate_generated_code(blocks: list[dict]) -> dict:
    """Validate all generated code blocks.

    Returns a dict with:
      - valid: bool
      - errors: list of {resource_type, name, errors} dicts
      - warnings: list of non-blocking warning strings
      - total_blocks: int
      - valid_blocks: int
      - hcl_syntax_valid: bool (whether the rendered HCL parses successfully)
    """
    all_errors: list[dict] = []
    warnings: list[str] = []
    valid_count = 0

    for block in blocks:
        block_type = block.get("resource_type", "")
        name = block.get("name", "")
        config = block.get("config", {})
        errors = validate_generated_block(block_type, name, config)
        if errors:
            all_errors.append({
                "resource_type": block_type,
                "name": name,
                "errors": errors,
            })
        else:
            valid_count += 1

    # HCL syntax validation: render all blocks and try to parse
    hcl_syntax_valid = True
    if blocks:
        rendered = render_optimized_project(blocks)
        syntax_ok, syntax_errors = _parse_hcl_syntax(rendered)
        hcl_syntax_valid = syntax_ok
        if not syntax_ok:
            warnings.extend(syntax_errors)

    is_valid = len(all_errors) == 0 and hcl_syntax_valid

    # Determine validation status label
    if is_valid:
        validation_status = "copy_paste_ready"
        validation_label = "Copy-paste ready"
    else:
        validation_status = "requires_validation"
        validation_label = "Generated suggestion — requires validation"

    return {
        "valid": is_valid,
        "validation_status": validation_status,
        "validation_label": validation_label,
        "errors": all_errors,
        "warnings": warnings,
        "total_blocks": len(blocks),
        "valid_blocks": valid_count,
        "hcl_syntax_valid": hcl_syntax_valid,
    }
